#!/usr/bin/env python3
"""Generate backend/database/seed/catalog.sql from the learning catalog.

The apps carry their lessons in packages/learning_core (catalog.dart). The
server only needs the skeleton — domain → topic (learning path) → skill, with
both titles — so that uploaded progress ("path"/"skill" slugs) can be matched
to rows. This script keeps the two in step; tests/db/test_catalog_seed.py
fails if the committed seed drifts from catalog.dart.

Usage:  python3 tools/generate_catalog_seed.py [--check]
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / "packages" / "learning_core" / "lib" / "src" / "catalog.dart"
SEED = ROOT / "backend" / "database" / "seed" / "catalog.sql"

# Which domain each learning path belongs to. A new path must be added here.
DOMAINS = {
    "algebra": ("الجبر", "Algebra", ["linear-equations", "quadratics"]),
    "numbers": ("الأعداد والعمليات", "Numbers and operations", ["fractions"]),
}

_ENTRY = re.compile(
    r"\b(LearningPath|Skill)\(\s*id:\s*'([a-z0-9-]+)',\s*"
    r"title:\s*Bilingual\(\s*'((?:[^'\\]|\\.)*)',\s*'((?:[^'\\]|\\.)*)'",
    re.S,
)


def parse_catalog(text: str) -> list[dict]:
    """Paths in file order, each with its skills in file order."""
    paths: list[dict] = []
    for kind, slug, ar, en in _ENTRY.findall(text):
        entry = {"slug": slug, "ar": ar.replace("\\'", "'"), "en": en.replace("\\'", "'")}
        if kind == "LearningPath":
            paths.append({**entry, "skills": []})
        else:
            if not paths:
                raise ValueError(f"skill {slug} appears before any learning path")
            paths[-1]["skills"].append(entry)
    return paths


def _q(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def render(paths: list[dict]) -> str:
    domain_of = {p: d for d, (_, _, ps) in DOMAINS.items() for p in ps}
    missing = [p["slug"] for p in paths if p["slug"] not in domain_of]
    if missing:
        raise ValueError(f"no domain for learning path(s): {missing} — add them to DOMAINS")
    out = [
        "-- GENERATED by tools/generate_catalog_seed.py from packages/learning_core.",
        "-- Do not edit by hand. Safe to run more than once (upserts by slug).",
        "-- Lesson text stays in the apps; this is only the skeleton that",
        "-- progress uploads are matched against.",
        "",
    ]
    for order, (dslug, (dar, den, _)) in enumerate(DOMAINS.items()):
        out.append(
            "insert into public.math_domains (slug, title_ar, title_en, sort_order) values "
            f"({_q(dslug)}, {_q(dar)}, {_q(den)}, {order})\n"
            "  on conflict (slug) do update set title_ar = excluded.title_ar,"
            " title_en = excluded.title_en, sort_order = excluded.sort_order;"
        )
    out.append("")
    for path in paths:
        dslug = domain_of[path["slug"]]
        out.append(
            "insert into public.math_topics (domain_id, slug, title_ar, title_en)\n"
            f"  select id, {_q(path['slug'])}, {_q(path['ar'])}, {_q(path['en'])}"
            f" from public.math_domains where slug = {_q(dslug)}\n"
            "  on conflict (domain_id, slug) do update set title_ar = excluded.title_ar,"
            " title_en = excluded.title_en;"
        )
        for skill in path["skills"]:
            out.append(
                "insert into public.skills (topic_id, slug, title_ar, title_en)\n"
                f"  select t.id, {_q(skill['slug'])}, {_q(skill['ar'])}, {_q(skill['en'])}"
                " from public.math_topics t join public.math_domains d on d.id = t.domain_id"
                f" where d.slug = {_q(dslug)} and t.slug = {_q(path['slug'])}\n"
                "  on conflict (topic_id, slug) do update set title_ar = excluded.title_ar,"
                " title_en = excluded.title_en;"
            )
        out.append("")
    return "\n".join(out)


def main() -> int:
    text = render(parse_catalog(CATALOG.read_text(encoding="utf-8")))
    if "--check" in sys.argv:
        if not SEED.exists() or SEED.read_text(encoding="utf-8") != text:
            print("seed is out of date: run python3 tools/generate_catalog_seed.py")
            return 1
        return 0
    SEED.parent.mkdir(parents=True, exist_ok=True)
    SEED.write_text(text, encoding="utf-8")
    print(f"wrote {SEED.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
